#!/usr/bin/env python3
"""Builds js/geo/land.js (+ land-hi.js): Japan's land outline and prefecture borders at several levels of detail.

Source: 地球地図日本 (Global Map Japan, 国土地理院 / GSI) prefecture polygons, as converted by github.com/dataofjapan/land (japan.geojson).
    git clone --depth 1 https://github.com/dataofjapan/land /tmp/geo/land
    python3 tools/import/build-land.py --geojson /tmp/geo/land/japan.geojson

Each level keeps `rings` (land polygons, used for the fill and the coastline stroke) and `borders` (edges shared by two prefectures).
Levels are simplified with Douglas-Peucker; land.js is small, the mid and hi levels are separate files that the page only loads as you zoom in.
Polylines are Google-encoded (1e5), like the track shapes.
"""
import argparse, json, math, os

ap = argparse.ArgumentParser()
ap.add_argument('--geojson', required=True)
ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', '..', 'js', 'geo'))
args = ap.parse_args()

# (tolerance in metres, smallest island kept: bbox extent in metres)
LODS = [(900, 4000), (250, 900), (45, 0)]
KX = 111320 * math.cos(math.radians(36)); KY = 110574


def enc(pts):
    out, plat, plon = [], 0, 0
    for lon, lat in pts:
        la, lo = round(lat * 1e5), round(lon * 1e5)
        for v in (la - plat, lo - plon):
            v = ~(v << 1) if v < 0 else v << 1
            while v >= 0x20:
                out.append(chr((0x20 | (v & 0x1f)) + 63)); v >>= 5
            out.append(chr(v + 63))
        plat, plon = la, lo
    return ''.join(out)


def rdp(pts, tol):
    """Douglas-Peucker on an open polyline of (lon, lat); distances in metres."""
    n = len(pts)
    if n < 3: return list(pts)
    xy = [(p[0] * KX, p[1] * KY) for p in pts]
    keep = [False] * n; keep[0] = keep[-1] = True
    stack = [(0, n - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = xy[a]; bx, by = xy[b]; dx, dy = bx - ax, by - ay; L = dx * dx + dy * dy
        far, fi = -1.0, -1
        for i in range(a + 1, b):
            px, py = xy[i]
            if L == 0: d = math.hypot(px - ax, py - ay)
            else:
                t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / L))
                d = math.hypot(px - ax - t * dx, py - ay - t * dy)
            if d > far: far, fi = d, i
        if far > tol:
            keep[fi] = True; stack.append((a, fi)); stack.append((fi, b))
    return [p for p, k in zip(pts, keep) if k]


def rdp_ring(ring, tol):
    """A closed ring: split at the point furthest from the start so both halves are proper open lines."""
    pts = ring[:-1] if ring[0] == ring[-1] else ring
    if len(pts) < 4: return None
    x0, y0 = pts[0]
    fi = max(range(len(pts)), key=lambda i: math.hypot((pts[i][0] - x0) * KX, (pts[i][1] - y0) * KY))
    a = rdp(pts[:fi + 1], tol); b = rdp(pts[fi:] + [pts[0]], tol)
    out = a[:-1] + b[:-1]
    return out if len(out) >= 3 else None


def extent(pts):
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
    return max((max(xs) - min(xs)) * KX, (max(ys) - min(ys)) * KY)


gj = json.load(open(args.geojson))
rings = []   # (ring id, [(lon, lat)])
for fi, f in enumerate(gj['features']):
    g = f['geometry']
    for poly in (g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]):
        if poly: rings.append((len(rings), [(round(x, 5), round(y, 5)) for x, y in poly[0]]))   # outer rings only

# edges shared by two rings are prefecture borders
ekey = lambda a, b: (a, b) if a < b else (b, a)
count, owner = {}, {}
for rid, r in rings:
    for a, b in zip(r, r[1:]):
        k = ekey(a, b); count[k] = count.get(k, 0) + 1; owner.setdefault(k, rid)
borders = []
for rid, r in rings:
    run = []
    for a, b in zip(r, r[1:]):
        k = ekey(a, b)
        if count[k] == 2 and owner[k] == rid:
            if not run: run = [a]
            run.append(b)
        elif run: borders.append(run); run = []
    if run: borders.append(run)

levels = []
for tol, minsize in LODS:
    rs = []
    for rid, r in rings:
        if minsize and extent(r) < minsize: continue
        s = rdp_ring(r, tol)
        if s: rs.append(enc(s + [s[0]]))
    bs = []
    if tol > 100:   # the detailed level draws borders as part of the ring outlines
        for b in borders:
            if extent(b) < minsize / 2: continue
            s = rdp(b, tol)
            if len(s) >= 2: bs.append(enc(s))
    levels.append({'rings': rs, 'borders': bs})

HDR = ('/* Auto-generated by tools/import/build-land.py — DO NOT EDIT BY HAND.\n'
       ' * Land outline and prefecture borders: 地球地図日本 (Global Map Japan), 国土地理院 / Geospatial Information Authority of Japan,\n'
       ' * via github.com/dataofjapan/land. Simplified for display. */\n')
os.makedirs(args.out, exist_ok=True)
def write(name, lv, start):
    js = HDR + "(function(g){g.TRS_LAND=g.TRS_LAND||{};g.TRS_LAND[%d]=%s;})(typeof window!=='undefined'?window:globalThis);\n" % (start, json.dumps(lv, separators=(',', ':')))
    open(os.path.join(args.out, name), 'w').write(js)
    return len(js) // 1024
sizes = [write('land.js', levels[0], 0), write('land-mid.js', levels[1], 1), write('land-hi.js', levels[2], 2)]
print('rings', len(rings), 'border runs', len(borders), '| KB per level (base, mid, hi):', sizes, '| rings per level', [len(l['rings']) for l in levels])
